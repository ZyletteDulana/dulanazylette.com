(function ($) {

    /**
     * INIT DATATABLE
     */
    window.initDataTable = function (selector, options = {}) {

        const defaults = {
            order: [[0, 'desc']],
            title: "Report",
            filenamePrefix: "POS_Report",
            subtitle: "Data as of"
        };

        const config = { ...defaults, ...options };

        $(selector).each(function () {

            if ($.fn.DataTable.isDataTable(this)) {
                $(this).DataTable().destroy();
            }

            $(this).DataTable({
                order: config.order,
                dom: "Bfrtip",

                buttons: getExportButtons(config)
            });

        });
    };


    /**
     * BUTTON SET
     */
    function getExportButtons(config) {
        return [
            createExportButton("copy", "Copy", "btn-secondary", config),
            createExportButton("excel", "Export to Excel", "btn-success", config, true),
            createExportButton("csv", "Export to CSV", "btn-primary", config, true),
            createExportButton("print", "Print", "btn-dark", config, false, true)
        ];
    }


    /**
     * CREATE BUTTON
     */
    function createExportButton(type, text, btnClass, config, withFileName = false, isPrint = false) {

        return {
            extend: type,
            text: text,
            className: `btn ${btnClass} btn-sm`,
           
            ...(withFileName && {
                filename: function () {
                    return buildFileName(config);
                },

                title: "Instambay FoodHub Report"
            }),

            exportOptions: {
                columns: ":visible:not(.export-ignore)",

                format: {
                    body: function (data, row, column, node) {

                        let $node = $(node).clone();

                        // remove hidden elements
                        $node.find(".d-none").remove();

                        let text = $node.text().trim();

                        // currency cleanup
                        if ($(node).hasClass("export-currency")) {
                            text = text.replace(/[₱,]/g, "₱");
                        }

                        // date handling (use hidden raw value)
                        if ($(node).hasClass("export-date")) {
                            let raw = $(node).find(".d-none").text().trim();

                            // ALWAYS return something
                            return raw !== "" ? raw : text;
                        }

                        return text;
                    }
                }
            },

            ...(isPrint && {
                customize: function (win) {

                    $(win.document.body)
                        .css({
                            fontSize: '12px',
                            padding: '20px'
                        });

                    $(win.document.body).find('h1, h2, h3, h4, h5').remove();

                    $(win.document.body).prepend(`
                        <div style="text-align:center; margin-bottom:20px;">
                            <h2 style="margin:0;">${config.title}</h2>
                            <p style="font-size: 18px;"> Generated by Instambay FoodHub </p><br>
                            <p style="font-size: 18px;">
                                ${config.subtitle}: 
                                ${new Date().toLocaleString()}
                            </p>
                        </div>
                    `);
                }
            })
        };
    }


    /**
     * FILENAME BUILDER
     */
    function buildFileName(config) {

        let d = new Date();

        let date = d.getFullYear() + '-' +
            String(d.getMonth() + 1).padStart(2, '0') + '-' +
            String(d.getDate()).padStart(2, '0');

        return `${config.filenamePrefix}_${date}`;
    }

})(jQuery);

